const GAP = 14;

/**
 * Lay out a word as one SVG path string per glyph.
 * Returns { width, paths } in glyph units (height 100), starting at x = 0.
 */
export function layoutText(text, gap = GAP) {
    const paths = [];
    let x = 0;
    for (const ch of text.toUpperCase()) {
        const glyph = GLYPHS[ch];
        if (!glyph) continue;
        if (glyph.d.length) {
            paths.push(glyph.d.map(poly => 'M' + poly.map(([px, py]) => `${px + x},${py}`).join('L') + 'Z').join(''));
        }
        x += glyph.w + gap;
    }
    return { width: Math.max(0, x - gap), paths };
}
